export function t(language, key, params = {}) {
  const langMessages = messages[language] || messages.en;
  const template = langMessages[key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`));
}

export function gameName(language, game) {
  const key = `game.${game.id}.name`;
  const translated = t(language, key);
  return translated === key ? game.name : translated;
}

export function gameInstructions(language, game) {
  const key = `game.${game.id}.instructions`;
  const translated = t(language, key);
  return translated === key ? game.instructions : translated;
}
